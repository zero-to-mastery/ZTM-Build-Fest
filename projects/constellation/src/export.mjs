import { username } from './constellation.mjs';
import { CONFIG_VERSION, normalizeConfig } from './config-schema.mjs';

export const projectUrl = 'https://github.com/mnichols08/constellation';

export function installationLinks(repository, workflow) {
  const target = repository.trim();
  if (!/^[a-z\d][a-z\d-]*\/[a-z\d_.-]+$/i.test(target) || ['.', '..'].includes(target.split('/')[1])) throw new Error('Enter the workflow repository as owner/repository.');
  const [owner, repo] = target.split('/');
  const base = `https://github.com/${encodeURIComponent(owner)}/${encodeURIComponent(repo)}`;
  const install = new URL(`${base}/new/HEAD`);
  install.searchParams.set('filename', '.github/workflows/constellation.yml');
  install.searchParams.set('value', workflow);
  const create = new URL('https://github.com/new');
  create.searchParams.set('name', repo);
  create.searchParams.set('visibility', 'public');
  create.searchParams.set('readme', '1');
  return {
    // Large custom CSS can exceed browser/server URL limits. Keep copy/download available.
    install: install.href.length <= 8000 ? install.href : null,
    create: create.href,
    actions: `${base}/actions/workflows/constellation.yml`,
  };
}

export function readmeSnippet(account, repository, filename = 'constellation.svg') {
  const name = account ? username(account) : 'My';
  const target = repository?.trim() || (account ? `${username(account)}/${username(account)}` : 'YOUR_USERNAME/YOUR_REPOSITORY');
  if (!/^[a-z\d][a-z\d-]*\/[a-z\d_.-]+$/i.test(target) && target !== 'YOUR_USERNAME/YOUR_REPOSITORY') throw new Error('Enter the workflow repository as owner/repository.');
  if (!/^[a-z\d][a-z\d._-]{0,120}\.svg$/i.test(filename)) throw new Error('Use a safe .svg filename for a GitHub README image.');
  const path = target.split('/').map(encodeURIComponent).join('/');
  const image = `https://raw.githubusercontent.com/${path}/output/${encodeURIComponent(filename)}`;
  return `[![${name} GitHub constellation](${image})](${projectUrl})\n\nMade with [GitHub Constellation](${projectUrl}) by [@mnichols08](https://github.com/mnichols08).`;
}

export function renderWorkflow(_account, options, publishing = {}) {
  const { activityData, codingRhythmData, historyData, accountData, organizationData, ...configuration } = options;
  const normalized = normalizeConfig(configuration, { trustedCSS: true });
  // JSON escapes preserve literal CSS dollars while preventing GitHub Actions
  // from interpreting user-authored CSS as workflow expressions.
  const json = JSON.stringify({ ...normalized, version: CONFIG_VERSION }, null, 2).replace(/\$/g, '\\u0024');
  const config = json.split('\n').map(line => `            ${line}`).join('\n');
  const filename = publishing.filename || 'constellation.svg';
  if (!/^[a-z\d][a-z\d._-]{0,120}\.svg$/i.test(filename)) throw new Error('Use a safe .svg filename for an automatic GitHub README workflow.');
  const branch = publishing.branch || 'output';
  if (!/^[a-zA-Z0-9][a-zA-Z0-9._/-]{0,127}$/.test(branch) || branch.includes('..') || branch.endsWith('/') || branch.includes('//')) throw new Error('Enter a safe output branch name.');
  if (publishing.story && !['auto', 'projects', 'technical-shape', 'journey'].includes(publishing.story))
    throw new Error('Choose a supported publishing story.');
  if (publishing.story && ![480, 900].includes(publishing.targetWidth))
    throw new Error('Choose a 480px or 900px publishing width.');
  return `# Save as .github/workflows/constellation.yml
# Generated by GitHub Constellation. Settings and CSS match the preview.
name: Daily constellation
on:
  schedule:
    - cron: '17 6 * * *'
  workflow_dispatch:
permissions:
  contents: write
concurrency:
  group: constellation-output-\u0024{{ github.repository }}
  cancel-in-progress: false
jobs:
  generate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v6
      - uses: mnichols08/constellation@${publishing.story ? 'main' : 'v3'}
        with:
          publish: 'true'
          output: '${filename}'
          output-branch: '${branch}'${publishing.story ? `\n          story: '${publishing.story}'\n          target-width: '${publishing.targetWidth}'` : ''}${publishing.sourceAccount || options.accountData?.type === 'Organization' || options.accountType === 'organization' || options.organizationUser ? `\n          username: '${username(_account)}'` : ''}
          config-json: |
${config}
`;
}
